from pathlib import Path
from datetime import datetime
from reportlab.lib.pagesizes import A4, landscape
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from docx import Document

def safe_name(s):
    return ''.join(c if c.isalnum() or c in '-_' else '_' for c in str(s))[:70] or 'report'

def make_report(title, headers, rows, folder, stem):
    folder=Path(folder); folder.mkdir(parents=True,exist_ok=True)
    stamp=datetime.now().strftime('%Y%m%d_%H%M%S'); base=f'{safe_name(stem)}_{stamp}'
    pdf=folder/(base+'.pdf'); docx=folder/(base+'.docx')
    styles=getSampleStyleSheet(); story=[Paragraph(title,styles['Title']),Spacer(1,12),Paragraph('Generated by SmartExam',styles['Normal']),Spacer(1,12)]
    data=[list(headers)]+[list(map(str,r)) for r in rows]
    t=Table(data,repeatRows=1)
    t.setStyle(TableStyle([('BACKGROUND',(0,0),(-1,0),colors.HexColor('#183153')),('TEXTCOLOR',(0,0),(-1,0),colors.white),('GRID',(0,0),(-1,-1),.5,colors.grey),('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,colors.HexColor('#eef3f8')]),('FONTSIZE',(0,0),(-1,-1),8),('VALIGN',(0,0),(-1,-1),'MIDDLE'),('PADDING',(0,0),(-1,-1),5)]))
    story.append(t); SimpleDocTemplate(str(pdf),pagesize=landscape(A4),rightMargin=24,leftMargin=24).build(story)
    d=Document(); d.add_heading(title,0); d.add_paragraph('Generated by SmartExam')
    table=d.add_table(rows=1, cols=len(headers)); table.style='Table Grid'
    for c,h in zip(table.rows[0].cells,headers): c.text=str(h)
    for row in rows:
        cells=table.add_row().cells
        for c,v in zip(cells,row): c.text=str(v)
    d.save(docx)
    return pdf.name,docx.name
